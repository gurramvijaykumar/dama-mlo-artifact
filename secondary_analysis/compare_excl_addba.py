"""Compare the all-run reference with the secondary analysis "excluding
trace-confirmed ADDBA-expiry cases" (2026-10-03).

Reads
  results/runs.jsonl + results/states_*.json                     all-run reference
  analysis_excl_addba_20261003/results/{runs.jsonl,states_*.json,excluded_addba.jsonl}
and writes analysis_excl_addba_20261003/COMPARISON.md and comparison.json.

For every State x link mode of each code-2.1 sensitivity sweep it reports the
number of matched seeds retained (n), the MAP 1 - MAP 4 difference in sum-log and
sum throughput, its Welch 95% CI and Welch p-value (independent-sample test, as in
the frozen tables; not a paired analysis), the estimated ranking (sign of the
difference) and whether p < 0.05, i.e. whether the data support that ranking. Estimates and p-values are
recomputed from runs.jsonl and checked against the states JSON of each side.

  python3 compare_excl_addba.py
"""

import json
import os

import numpy as np
from scipy import stats

import analyze as A
from experiments import STATE_SEEDS, STATES
from simlib import CODE_VERSION

HERE = os.path.dirname(os.path.abspath(__file__))
EXCL = os.path.join(HERE, "analysis_excl_addba_20261003")
MODES = ["mlo", "mloConfined"]
# (label, states JSON tag, args filter) -- the code-2.1 sweeps feeding tab_sens / tab_backhaul
SWEEPS = [("baseline 80 MHz", "_v21", {}),
          ("backhaul 20 MHz", "_bh20", {"backhaulWidth": 20}),
          ("backhaul 160 MHz", "_bh160", {"backhaulWidth": 160}),
          ("UDP", "_UDP", {"useTcp": "false"}),
          ("downlink", "_downlink", {"downlink": "true"}),
          ("near (10 m)", "_near", {"staDist": 10.0})]
METRICS = ["sumLog", "sumTput"]


def load_index(root, filt):
    """(mode, n4Rate, scenario, x, y, seed) -> out for code-2.1 runs matching BASE+filt."""
    # load_runs reads the module global RUNS_FILE; point it at this tree's runs.jsonl
    A.RUNS_FILE = os.path.join(root, "results", "runs.jsonl")
    return A.index(A.load_runs(filt, version=CODE_VERSION))


def welch(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    d = a.mean() - b.mean()
    va, vb = a.var(ddof=1) / len(a), b.var(ddof=1) / len(b)
    se = np.sqrt(va + vb)
    if se == 0:
        return d, (d, d), 1.0
    df = (va + vb) ** 2 / (va ** 2 / (len(a) - 1) + vb ** 2 / (len(b) - 1))
    h = stats.t.ppf(0.975, df) * se
    p = stats.ttest_ind(a, b, equal_var=False).pvalue
    return float(d), (float(d - h), float(d + h)), float(p)


def cells(root, tag, filt):
    idx = load_index(root, filt)
    js = json.load(open(os.path.join(root, "results", f"states{tag}.json")))
    out = {}
    for mode in MODES:
        for st in STATES:
            x, y, rate = st["n5X"], st["n5Y"], st["n4Rate"]
            common = [s for s in STATE_SEEDS
                      if (mode, rate, 1, x, y, s) in idx and (mode, rate, 2, x, y, s) in idx]
            c = {"n": len(common), "seeds": common}
            for m in METRICS:
                a = [idx[(mode, rate, 1, x, y, s)][m] for s in common]
                b = [idx[(mode, rate, 2, x, y, s)][m] for s in common]
                d, ci, p = welch(a, b)
                c[m] = {"d": d, "ci": ci, "p": p}
            j = js[f"{mode}|state{st['id']}"]
            # cross-check against the states JSON written by make_tables_figs.py
            assert j["n_common"] == c["n"], (root, tag, mode, st["id"])
            for m in METRICS:
                assert abs(j[f"delta_{m}_MAP1_minus_MAP4"] - c[m]["d"]) < 1e-9
                assert abs(j[f"welch_p_{m}_MAP1_vs_MAP4"] - c[m]["p"]) < 1e-9
            c["choice"] = j.get("choice", {})
            out[(mode, st["id"])] = c
    return out


def pref(d):
    return "MAP1" if d > 0 else "MAP4" if d < 0 else "tie"


def main():
    rows, md = [], []
    md += ["# All-run reference vs. secondary analysis excluding trace-confirmed ADDBA-expiry cases", "",
           "Generated by compare_excl_addba.py. Difference = MAP 1 minus MAP 4 on the matched seeds retained",
           "(a seed is kept only if both options have it). CI and p are Welch results: they treat the two options",
           "as independent samples, as in the frozen tables, even though the seeds are matched; this is NOT a",
           "paired analysis (a paired-difference check would be a separately labelled methodological check).",
           "Est. ranking = option with the higher mean (an estimate only). Supported = Welch p < 0.05; where it",
           "is 'no', the data do not establish a preferred option, whatever the estimated ranking.",
           "Excluded records: analysis_excl_addba_20261003/results/excluded_addba.jsonl.", ""]
    for label, tag, filt in SWEEPS:
        ref = cells(HERE, tag, filt)
        exc = cells(EXCL, tag, filt)
        changed = [k for k in ref if ref[k]["n"] != exc[k]["n"]]
        for k in ref:
            r, e = ref[k], exc[k]
            same = r["n"] == e["n"] and all(r[m]["d"] == e[m]["d"] for m in METRICS)
            assert same or k in changed, (label, k)
        md.append(f"## {label}: {len(changed)} of {len(ref)} comparisons changed")
        if not changed:
            md += ["", "Identical in both analyses (same seeds, estimates and p-values).", ""]
            continue
        md += ["", "| Mode | State | matched seeds n (ref -> excl) | seeds removed | metric | ref diff [Welch 95% CI]"
               " | excl diff [Welch 95% CI] | ref Welch p | excl Welch p | est. ranking ref -> excl"
               " | supported (p<0.05) ref -> excl |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
        for k in changed:
            r, e = ref[k], exc[k]
            gone = sorted(set(r["seeds"]) - set(e["seeds"]))
            for m in METRICS:
                rr, ee = r[m], e[m]
                row = {"sweep": label, "mode": k[0], "state": k[1], "metric": m,
                       "n_ref": r["n"], "n_excl": e["n"], "seeds_removed": gone,
                       "ref": rr, "excl": ee,
                       "pref_ref": pref(rr["d"]), "pref_excl": pref(ee["d"]),
                       "sig_ref": rr["p"] < 0.05, "sig_excl": ee["p"] < 0.05,
                       "choice": r["choice"]}
                rows.append(row)
                md.append(f"| {k[0]} | {k[1]} | {r['n']} -> {e['n']} | {gone} | {m} "
                          f"| {rr['d']:+.3f} [{rr['ci'][0]:+.3f}, {rr['ci'][1]:+.3f}] "
                          f"| {ee['d']:+.3f} [{ee['ci'][0]:+.3f}, {ee['ci'][1]:+.3f}] "
                          f"| {rr['p']:.3g} | {ee['p']:.3g} | {row['pref_ref']} -> {row['pref_excl']} "
                          f"| {'yes' if row['sig_ref'] else 'no'} -> {'yes' if row['sig_excl'] else 'no'} |")
        md.append("")
    flips = [r for r in rows if r["pref_ref"] != r["pref_excl"]]
    sigs = [r for r in rows if r["sig_ref"] != r["sig_excl"]]
    md += ["## Summary", "",
           f"- Changed comparisons: {len({(r['sweep'], r['mode'], r['state']) for r in rows})}",
           f"- Estimated-ranking flips (sign of the difference; not evidence by itself): {len(flips)}"
           + "".join(f"\n  - {r['sweep']} {r['mode']} State {r['state']} {r['metric']}: "
                     f"{r['pref_ref']} -> {r['pref_excl']}" for r in flips),
           f"- Changes in statistical support (Welch p<0.05): {len(sigs)}"
           + "".join(f"\n  - {r['sweep']} {r['mode']} State {r['state']} {r['metric']}: "
                     f"p {r['ref']['p']:.3g} -> {r['excl']['p']:.3g}" for r in sigs),
           "- Heuristic choices (RSSI/LoadAware/Airtime/AirtimeThr) use the scenario-0 runs, which are"
           " retained, so they are unchanged; only the option they are scored against can change.",
           "- Ranking support per changed comparison: see the 'supported' column; a ranking with 'no' in both"
           " analyses is unsupported in both, whether or not its sign changed.", ""]
    open(os.path.join(EXCL, "COMPARISON.md"), "w").write("\n".join(md))
    json.dump(rows, open(os.path.join(EXCL, "comparison.json"), "w"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
