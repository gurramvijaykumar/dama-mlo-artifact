"""Writes tables/tab_udp_excl.tex: UDP sensitivity comparisons that change when the trace-confirmed
ADDBA-expiry cases are excluded (secondary analysis). Source: comparison.json (compare_excl_addba.py)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
rows = [r for r in json.load(open(os.path.join(HERE, "comparison.json"))) if r["sweep"] == "UDP"]
CONF = {"mlo": "MLO", "mloConfined": "MLO-conf."}
MET = {"sumLog": "Sum-log", "sumTput": "Sum tput"}


def p(x):
    return "$<10^{-3}$" if x < 1e-3 else f"${x:.3f}$"


def cell(s):
    lo, hi = s["ci"]
    return f"${s['d']:+.3f}$ {{\\scriptsize [${lo:+.3f}$, ${hi:+.3f}$]}}"


body = []
last = None
for r in sorted(rows, key=lambda r: (r["mode"] != "mlo", r["state"], r["metric"] != "sumLog")):
    grp = (r["mode"], r["state"])
    head = [str(r["state"]), CONF[r["mode"]], f"{r['n_ref']} $\\to$ {r['n_excl']}"] if grp != last else ["", "", ""]
    if last is not None and grp != last:
        body.append("\\addlinespace")
    last = grp
    body.append(" & ".join(head + [MET[r["metric"]], cell(r["ref"]), p(r["ref"]["p"]),
                                   cell(r["excl"]), p(r["excl"]["p"])]) + " \\\\")
tex = r"""% generated by analysis_excl_addba_20261003/make_tab_udp_excl.py -- do not edit by hand
\begin{table*}[t]
\caption{UDP comparisons that change when trace-confirmed ADDBA-expiry cases are excluded (secondary analysis).}
\label{tab:udp_excl}
\centering
\small
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{clc l cc cc}
\toprule
 & & Seeds & & \multicolumn{2}{c}{All runs (primary)} & \multicolumn{2}{c}{Excl.\ ADDBA-expiry cases} \\
\cmidrule(lr){5-6}\cmidrule(lr){7-8}
State & Config. & & Metric & Diff.\ [95\% CI] & $p$ & Diff.\ [95\% CI] & $p$ \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}
\par\smallskip\footnotesize Welch's $t$-test and Welch 95\% CI, matched seeds retained: a seed is removed from both MAP options of a comparison, and the two options are still treated as independent samples (not a paired analysis). Diff.: MAP 1 minus MAP 4. Seeds: matched seeds in the primary $\to$ secondary analysis. Sum tput in Mbit/s. All other UDP entries of Table~\ref{tab:sens}, and every entry of the other sweeps, are identical in both analyses.
\end{table*}
"""
open(os.path.join(HERE, "..", "tables", "tab_udp_excl.tex"), "w").write(tex)
print(tex)
